import { SolarInputState, SolarCalculationResult } from '../types/solar';

export function calculateSolarSystem(input: SolarInputState): SolarCalculationResult {
  let dailyKwhNeeded = 0;
  let monthlyKwhNeeded = 0;
  let annualKwhNeeded = 0;

  // Determine energy demand based on calculation mode
  if (input.calculationMode === 'bill') {
    // If user enters bill, calculate kWh using tariff
    if (input.monthlyBill > 0 && input.tariffPerKwh > 0) {
      monthlyKwhNeeded = (input.monthlyBill / input.tariffPerKwh) * (input.offsetPercentage / 100);
    } else if (input.monthlyKwh > 0) {
      monthlyKwhNeeded = input.monthlyKwh * (input.offsetPercentage / 100);
    } else {
      monthlyKwhNeeded = 450 * (input.offsetPercentage / 100);
    }
    dailyKwhNeeded = monthlyKwhNeeded / 30;
    annualKwhNeeded = monthlyKwhNeeded * 12;
  } else if (input.calculationMode === 'appliances') {
    // Sum from appliance list
    const totalDailyWh = input.appliances.reduce((acc, app) => acc + (app.watts * app.quantity * app.dailyHours), 0);
    dailyKwhNeeded = totalDailyWh / 1000;
    monthlyKwhNeeded = dailyKwhNeeded * 30;
    annualKwhNeeded = dailyKwhNeeded * 365;
  } else if (input.calculationMode === 'area') {
    // Rooftop area constrained sizing
    // Average 550W panel requires approx 26 sq.ft
    const effectiveArea = input.availableRoofAreaSqFt * (input.usableAreaPercent / 100);
    const approxPanels = Math.floor(effectiveArea / 26);
    const maxKw = (approxPanels * input.panelWattage) / 1000;
    // Energy generated by this max array:
    const dailyGenFromArea = maxKw * input.peakSunHours * (1 - input.systemLossFactor);
    dailyKwhNeeded = dailyGenFromArea;
    monthlyKwhNeeded = dailyGenFromArea * 30;
    annualKwhNeeded = dailyGenFromArea * 365;
  }

  // Guard against 0 or negative
  if (dailyKwhNeeded <= 0) {
    dailyKwhNeeded = 10;
    monthlyKwhNeeded = 300;
    annualKwhNeeded = 3650;
  }

  // Solar Array Sizing (kWp):
  // Array (kWp) = Daily kWh / (Peak Sun Hours * (1 - System Loss))
  const derateMultiplier = Math.max(0.65, 1 - input.systemLossFactor);
  const effectiveSunHours = Math.max(2.5, input.peakSunHours * derateMultiplier);
  const rawArrayKw = dailyKwhNeeded / effectiveSunHours;

  // Number of panels
  const panelWatt = Math.max(300, input.panelWattage);
  const panelCount = Math.ceil((rawArrayKw * 1000) / panelWatt);
  const actualArrayKw = (panelCount * panelWatt) / 1000;

  // Inverter Sizing (kW):
  // Typically sized to handle array DC output with 1.15 to 1.25 sizing ratio
  const rawInverterKw = actualArrayKw / input.inverterOversizingRatio;
  // Standard inverter capacities: 3, 5, 6, 8, 10, 12, 15, 20, 25, 30, 50, 100 kW
  let recommendedInverterKw = Math.ceil(rawInverterKw * 10) / 10;
  if (recommendedInverterKw < 1) recommendedInverterKw = 1.5;

  // Inverter phase
  const inverterPhase = actualArrayKw >= 6 ? '3-Phase (400V)' : '1-Phase (230V)';

  // Battery Storage Sizing (Hybrid and Off-grid)
  const requiresBattery = input.systemType === 'hybrid' || input.systemType === 'off-grid';
  let batteryCapacityKwh = 0;
  let batteryCapacityAh = 0;

  if (requiresBattery) {
    // For off-grid, provide full autonomy. For hybrid, provide critical daily load backup (typically 70% of daily load * autonomy days)
    const backupLoadRatio = input.systemType === 'off-grid' ? 1.0 : 0.75;
    const backupDailyKwh = dailyKwhNeeded * backupLoadRatio;
    const dod = input.batteryChemistry === 'lifepo4' ? 0.85 : 0.50; // LiFePO4 vs Tubular Gel
    const inverterEfficiency = 0.92;

    batteryCapacityKwh = (backupDailyKwh * input.batteryAutonomyDays) / (dod * inverterEfficiency);
    // Standard system voltage is 48V
    const voltage = input.systemVoltage || 48;
    batteryCapacityAh = Math.round((batteryCapacityKwh * 1000) / voltage);
  }

  // Required Roof Space:
  // Each panel takes ~25-27 sq ft plus ~15% for inter-row spacing and walkways
  const sqFtPerPanel = (panelWatt / 1000) * 48; // ~26.4 sq ft for 550W
  const roofAreaRequiredSqFt = Math.round(panelCount * sqFtPerPanel * 1.15);
  const roofAreaRequiredSqM = Math.round(roofAreaRequiredSqFt * 0.092903);

  // Generation Estimates:
  const estimatedDailyGenerationKwh = Math.round((actualArrayKw * input.peakSunHours * derateMultiplier) * 10) / 10;
  const estimatedMonthlyGenerationKwh = Math.round(estimatedDailyGenerationKwh * 30);
  const estimatedAnnualGenerationKwh = Math.round(estimatedDailyGenerationKwh * 365);

  // Financial Estimates (in BDT or USD):
  const tariff = input.tariffPerKwh > 0 ? input.tariffPerKwh : 9.5; // BDT avg or input
  const estimatedMonthlySavings = Math.round(estimatedMonthlyGenerationKwh * tariff);
  const estimatedAnnualSavings = Math.round(estimatedAnnualGenerationKwh * tariff);

  // Capital Cost Estimation (Bangladesh Market Rates in BDT per Watt):
  // On-Grid: ~৳65 to ৳80 per Watt peak
  // Hybrid: ~৳95 to ৳125 per Watt peak (including LiFePO4 batteries)
  // Off-Grid: ~৳110 to ৳140 per Watt peak
  let costPerWattMin = 68;
  let costPerWattMax = 82;

  if (input.systemType === 'hybrid') {
    costPerWattMin = 95;
    costPerWattMax = 125;
  } else if (input.systemType === 'off-grid') {
    costPerWattMin = 110;
    costPerWattMax = 145;
  }

  const estimatedSystemCostMin = Math.round(actualArrayKw * 1000 * costPerWattMin);
  const estimatedSystemCostMax = Math.round(actualArrayKw * 1000 * costPerWattMax);
  const avgSystemCost = (estimatedSystemCostMin + estimatedSystemCostMax) / 2;

  const paybackPeriodYears = estimatedAnnualSavings > 0
    ? Math.round((avgSystemCost / estimatedAnnualSavings) * 10) / 10
    : 4.2;

  // Environmental Impact:
  // 1 kWh solar = ~0.72 kg CO2 avoided
  const co2OffsetTonsYear = Math.round(((estimatedAnnualGenerationKwh * 0.72) / 1000) * 10) / 10;
  // 1 tree absorbs ~21.7 kg CO2 per year
  const equivalentTreesPlanted = Math.round((co2OffsetTonsYear * 1000) / 21.7);

  return {
    dailyEnergyNeedKwh: Math.round(dailyKwhNeeded * 10) / 10,
    monthlyEnergyNeedKwh: Math.round(monthlyKwhNeeded),
    annualEnergyNeedKwh: Math.round(annualKwhNeeded),

    recommendedArrayKw: Math.round(rawArrayKw * 100) / 100,
    panelCount,
    panelWattage: panelWatt,
    actualArrayKw: Math.round(actualArrayKw * 100) / 100,

    recommendedInverterKw,
    inverterPhase,

    requiresBattery,
    batteryCapacityKwh: Math.round(batteryCapacityKwh * 10) / 10,
    batteryCapacityAh,
    batteryChemistry: input.batteryChemistry,
    batteryVoltage: input.systemVoltage || 48,

    roofAreaRequiredSqFt,
    roofAreaRequiredSqM,

    estimatedDailyGenerationKwh,
    estimatedMonthlyGenerationKwh,
    estimatedAnnualGenerationKwh,

    estimatedMonthlySavings,
    estimatedAnnualSavings,
    estimatedSystemCostMin,
    estimatedSystemCostMax,
    paybackPeriodYears,
    paybackYears: paybackPeriodYears,

    co2OffsetTonsYear,
    equivalentTreesPlanted,
  };
}

export function formatCurrency(amount: number, currency: 'BDT' | 'USD' = 'BDT'): string {
  if (currency === 'BDT') {
    return `৳${amount.toLocaleString('en-IN')}`;
  }
  return `$${amount.toLocaleString('en-US')}`;
}
